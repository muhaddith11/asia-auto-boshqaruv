-- ─────────────────────────────────────────────────────────────────────────────
-- KONTEYNERGA QO'LDA QO'YILGAN ZAPCHASTLAR (konteyner_items)
-- ─────────────────────────────────────────────────────────────────────────────
-- 3D konteyner ombori (/parts/konteyner) uchun: ombordan (`parts`) EMAS, tashqaridan
-- olib kelinib to'g'ridan-to'g'ri javonga qo'yilgan zapchastlar. Ombor qoldig'i,
-- kassa, sarmoya va zapchast hisobotlariga aralashmaydi.
--
-- narx — 1 donasining narxi (so'm), ogirlik — 1 donasining og'irligi (kg).
-- Kirish: faqat server API orqali (service_role), shuning uchun RLS yoqilgan,
-- siyosat yo'q — boshqa jadvallar kabi.
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.konteyner_items (
  id         bigint generated by default as identity primary key,
  javon      text not null check (javon ~ '^[AB][1-6]-[1-5]$'),
  nom        text not null check (length(btrim(nom)) > 0),
  narx       numeric check (narx is null or narx >= 0),
  soni       numeric not null default 1 check (soni > 0),
  ogirlik    numeric check (ogirlik is null or ogirlik >= 0),
  izoh       text,
  javon_tur  text check (javon_tur is null or javon_tur in
    ('motor','tormoz','filtr','elektr','osma','moy','shina','kuzov','akkum','boshqa')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.konteyner_items enable row level security;

create index if not exists konteyner_items_javon_idx on public.konteyner_items (javon);
